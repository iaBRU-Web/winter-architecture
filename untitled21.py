class HubSync:
    def __init__(self, repo_id):
        self.repo_id, self.api = repo_id, hf_api()
        self.api.create_repo(repo_id, exist_ok=True, private=True)
        self.q, self.busy = queue.Queue(maxsize=1), threading.Event()
        threading.Thread(target=self._loop, daemon=True).start()

    def _loop(self):
        while True:
            folder, msg = self.q.get()
            self.busy.set()
            try:
                self.api.upload_folder(repo_id=self.repo_id, folder_path=folder, commit_message=msg)
                print(f"[hub] uploaded: {msg}", flush=True)
            except Exception as e:
                print(f"[hub] upload failed ({e}); will retry at the next checkpoint", flush=True)
            finally:
                self.busy.clear()
                self.q.task_done()

    def push(self, folder, msg):
        if self.busy.is_set() or self.q.full():
            return False
        self.q.put_nowait((folder, msg))
        return True

    def flush(self):
        self.q.join()


def save_bundle(d, model, tok):
    from safetensors.torch import save_file
    os.makedirs(d, exist_ok=True)
    save_file({k: v.detach().cpu().contiguous() for k, v in model.state_dict().items()}, os.path.join(d, "model.safetensors"), metadata={"format": "pt"})
    cfg = model.config
    cfg.auto_map = {"AutoConfig": f"{MODULE_NAME}.BarameterConfig", "AutoModelForCausalLM": f"{MODULE_NAME}.BarameterForCausalLM"}
    cfg.save_pretrained(d)
    tok.save(d)
    model.mem.save(os.path.join(d, "memory"))
    src = globals().get("__file__")
    if src and os.path.exists(src):
        shutil.copy(src, os.path.join(d, MODULE_NAME + ".py"))


def load_bundle(path_or_repo, device, mmap=False):
    from safetensors.torch import load_file
    d = resolve_path(path_or_repo)
    cfg = BarameterConfig.from_pretrained(d)
    model = BarameterForCausalLM(cfg)
    model.load_state_dict(load_file(os.path.join(d, "model.safetensors")), strict=True)
    model.mem.load(os.path.join(d, "memory"), mmap)
