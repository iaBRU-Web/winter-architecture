ZERO_SUFFIX = ("mix.out.weight", "ffn.w2.weight", "wo.weight")


def grow_model(model, add_layers=0, new_d_model=None):
    old = model.config
    cfg = copy.deepcopy(old)
    D0, dh, g = old.d_model, old.head_dim, old.n_heads // old.n_kv_heads
    if new_d_model and new_d_model > D0:
        H1 = math.ceil(new_d_model / dh / g) * g  # keeps GQA group size so old heads keep their KV mapping
        cfg.d_model, cfg.n_heads, cfg.n_kv_heads = H1 * dh, H1, H1 // g
        cfg.ffn_hidden = int(round(old.ffn_hidden * cfg.d_model / D0 / 64)) * 64
    D1 = cfg.d_model
    n_old = old.n_layers
    ins = sorted({min(n_old - 1, max(1, round((j + 1) * n_old / (add_layers + 1)))) for j in range(add_layers)}) if add_layers else []
    types, new2old, oi = [], {}, 0
    for pos in range(n_old):
        while ins and ins[0] == pos:
            types.append("lin"); ins.pop(0)
        new2old[len(types)] = pos
        types.append(old.block_types[pos])
    while ins:
        types.append("lin"); ins.pop(0)
    inserted_before = lambda c: sum(1 for ni in range(len(types)) if ni not in new2old and ni < _new_index_of_old(new2old, c))
    old2new = {o: n for n, o in new2old.items()}
    shift = lambda c: (old2new[c - 1] + 1) if c >= 1 else 0  # count after old block c-1
    cfg.block_types, cfg.n_layers = types, len(types)
    cfg.read_after = [shift(c) for c in old.read_after]
    cfg.write_from = shift(old.write_from)
    cfg.growth_history = list(old.growth_history) + [{"add_layers": add_layers, "d_model": [D0, D1], "layers": [n_old, len(types)]}]
    new = BarameterForCausalLM(cfg).to(next(model.parameters()).device)
    read_new2old = {shift(c): c for c in old.read_after}
    osd = model.state_dict()

    def old_name(nm):
        p = nm.split(".")
        if p[0] == "blocks":
            if int(p[1]) not in new2old:
                return None
            p[1] = str(new2old[int(p[1])])
        elif p[0] == "reads":
            p[1] = str(read_new2old[int(p[1])])
        return ".".join(p)

    with torch.no_grad():
        for name, p in new.state_dict().items():
            on = old_name(name)
            if name.endswith(ZERO_SUFFIX):
                p.zero_()
            if on is None:
                continue
            src = osd[on].to(p.dtype)
            if name == "embed.weight":
                p.zero_()
            tail = ".".join(name.split(".")[-2:])
            if tail in ("n1.weight", "n2.weight", "norm.weight") and D1 != D0:
                p.fill_(1.0)
                src = src * math.sqrt(D0 / D1)  # zero-padded dims change RMS; compensate so outputs are identical
            assert all(a >= b for a, b in zip(p.shape, src.shape)), name
            p[tuple(slice(0, s) for s in src.shape)] = src
    new.mem = model.mem
    new.mem.cfg = cfg
    return new


def _new_index_of_old(new2old, c):
    return 0


