class Tok:
    pad, eos, user, asst = 0, 1, 2, 3

    def __init__(self, enc):
        self.enc = enc

    @property
    def vocab_size(self):
        return self.enc.get_vocab_size()

    def encode(self, t):
        return self.enc.encode(t).ids

    def decode(self, ids):
        return self.enc.decode([int(i) for i in ids], skip_special_tokens=False)

    def save(self, d):
        os.makedirs(d, exist_ok=True)
        self.enc.save(os.path.join(d, "tokenizer.json"))
        try:
            from transformers import PreTrainedTokenizerFast
            PreTrainedTokenizerFast(tokenizer_object=self.enc, pad_token="<pad>", eos_token="<eos>").save_pretrained(d)
        except Exception:
            pass

    @staticmethod
    def load(d):
        from tokenizers import Tokenizer
        return Tok(Tokenizer.from_file(os.path.join(d, "tokenizer.json")))

    @staticmethod
    def train(texts, vocab_size):
        from tokenizers import Tokenizer, models, pre_tokenizers, decoders, trainers
        enc = Tokenizer(models.BPE())
        enc.pre_tokenizer = pre_tokenizers.ByteLevel(add_prefix_space=False)
        enc.decoder = decoders.ByteLevel()
        tr = trainers.BpeTrainer(vocab_size=vocab_size, special_tokens=SPECIALS, show_progress=False,
                                 initial_alphabet=pre_tokenizers.ByteLevel.alphabet())
        enc.train_from_iterator(texts, tr)
        return Tok(enc)


def format_row(r):
    if "instruction" in r:
        u = r["instruction"] + (("\n" + r["input"]) if r.get("input") else "")
        a = r.get("output") or r.get("response")
    elif "question" in r:
        u, a = r["question"], r.get("response") or r.get("answer")
    elif "prompt" in r:
        u, a = r["prompt"], r.get("response") or r.get("completion") or r.get("chosen")
    elif "text" in r:
        return r["text"]
    else:
        return None
    if not u or not a:
        return None
    return f"<|user|>\n{u}\n<|assistant|>\n{a}"


def load_rows(name, split="train", streaming=False, max_examples=0, holdout=500):
    """Returns (make_rows(epoch) -> iterator of strings, heldout list of strings)."""
    from datasets import load_dataset
    ds = load_dataset(name, split=split, streaming=streaming)
    if streaming:
        held = [t for t in (format_row(r) for r in ds.take(holdout)) if t]
        tr = ds.skip(holdout)
        if max_examples:
            tr = tr.take(max_examples)
    else:
        n = len(ds)
        held = [t for t in (format_row(ds[i]) for i in range(min(holdout, n))) if t]
        tr = ds.select(range(min(holdout, n), n if not max_examples else min(n, holdout + max_examples)))

    def make_rows(epoch):
        src = tr.shuffle(seed=epoch, buffer_size=10000) if streaming else tr.shuffle(seed=epoch)
        for r in src:
            t = format_row(r)
            if t:
                yield t

    return make_rows, held


def _pack(tok, texts, L):
    buf, batch = [], []

    def flush():
        for e in tok.enc.encode_batch(batch):
            buf.extend(e.ids)
            buf.append(tok.eos)
        batch.clear()

    for t in texts:
        batch.append(t)
        if len(batch) >= 256:
            flush()
            while len(buf) >= L:
                yield np.asarray(buf[:L], np.int64)
                del buf[:L]
    if batch:
        flush()
    while len(buf) >= L:
        yield np.asarray(buf[:L], np.int64)
        del buf[:L]


def window_stream(tok, make_rows, L, skip=0):
    ep, n = 0, 0
    while True:
        got = False
        for w in _pack(tok, make_rows(ep), L):
            got = True
            n += 1
            if n > skip:
                yield w
        if not got:
            return
        ep += 1


