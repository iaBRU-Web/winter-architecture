def format_row(r):
    if "instruction" in r:
        u = r["instruction"] + (("\n" + r["input"]) if r.get("input") else "")
        a = r.get("output") or r.get("response")
    elif "question" in r:
        u, a = r["question"], r.get("response") or r.get("answer")
    elif "prompt" in r:
        u, a = r["prompt"], r.get("response") or r.get("completion") or r.get("chosen")
    elif "text" in r:
        return r["text"]
    else:
        return None
    if not u or not a:
        return None
    return f"<|user|>\n{u}\n<|assistant|>\n{a}"


def load_rows(name, split="train", streaming=False, max_examples=0, holdout=500):
    """Returns (make_rows(epoch) -> iterator of strings, heldout list of strings)."""
    from datasets import load_dataset
    ds = load_dataset(name, split=split, streaming=streaming)
    if streaming:
        held = [t for t in (format_row(r) for r in ds.take(holdout)) if t]
        tr = ds.skip(holdout)
        if max_examples:
            tr = tr.take(max_examples)
    else:
        n = len(ds)
        held = [t for t in (format_row(ds[i]) for i in range(min(holdout, n))) if t]
        tr = ds.select(range(min(holdout, n), n if not max_examples else min(n, holdout + max_examples)))

    def make_rows(epoch):
        src = tr.shuffle(seed=epoch, buffer_size=10000) if streaming else tr.shuffle(seed=epoch)
        for r in src:
            t = format_row(r)
            if t:
                yield t

    return make_rows, held


def _pack(tok, texts, L):
    buf, batch = [], []

    def flush():
        for e in tok.enc.encode_batch(batch):
            buf.extend(e.ids)
            buf.append(tok.eos)
        batch.clear()

    for t in texts:
        batch.append(t)
        if len(batch) >= 256:
            flush()
            while len(buf) >= L:
                yield np.asarray(buf[:L], np.int64)
                del buf[:L]
    if batch:
        flush()
    while len(buf) >= L:
        yield np.asarray(buf[:L], np.int64)
        del buf[:L]


def window_stream(tok, make_rows, L, skip=0):
    ep, n = 0, 0
    while True:
        got = False
        for w in _pack(tok, make_rows(ep), L):
            got = True
            n += 1
            if n > skip:
                yield w
        if not got:
            return
        ep += 1


# ----------------------------------------------------------------------------------------------
# Optimiser (Muon for 2-D hidden weights, AdamW for the rest)
# ----------------------------------------------------------------------------------------------
def newton_schulz(G, steps=5):
    a, b, c = 3.4445, -4.7750, 2.0315
    X = G.float()
    X = X / (X.norm() + 1e-7)
    tr = X.shape[0] > X.shape[1]
    if tr:
        X = X.T
    for _ in range(steps):
        A = X @ X.T
        X = a * X + (b * A + c * A @ A) @ X
    return X.T if tr else X


class Muon(torch.optim.Optimizer):
    def __init__(self, params, lr=0.02, momentum=0.95, wd=0.01):
        super().__init__(params, dict(lr=lr, momentum=momentum, wd=wd))

    @torch.no_grad()
    def step(self, closure=None):
        for g in self.param_groups:
            for p in g["params"]:
                if p.grad is None:
                    continue
                st = self.state[p]
                if "buf" not in st:
                    st["buf"] = torch.zeros_like(p)
                st["buf"].mul_(g["momentum"]).add_(p.grad)
                u = newton_schulz(p.grad.add(st["buf"], alpha=g["momentum"]))
                u = u * max(1.0, p.shape[0] / p.shape[1]) ** 0.5
                p.mul_(1 - g["lr"] * g["wd"]).add_(u.to(p.dtype), alpha=-g["lr"])


def build_optimizers(model, lr_muon, lr_adam, wd=0.01):
    mu, ad = [], []
    for n, p in model.named_parameters():
        (mu if p.ndim == 2 and "embed" not in n else ad).append(p)
    return [Muon(mu, lr=lr_muon, wd=wd), torch.optim.AdamW(ad, lr=lr_adam, betas=(0.9, 0.95), weight_decay=0.0)]


def lr_mult(prog, warm=0.03):
    if prog < warm:
        return max(prog / warm, 0.02)
    return 0.1 + 0.9 * 0.5 * (1 + math.cos(math.pi * min(1.0, (prog - warm) / (1 - warm))))


