def pick_device():
    return torch.device("cuda" if torch.cuda.is_available() else "cpu")


def write_batch(model, ids, tag, writes=None):
    writes = writes or model.last_writes
    if writes is None:
        return
    C = model.config.write_chunk
    nc = writes["keys"].shape[1]
    tokens = ids[:, : nc * C].reshape(-1, C).cpu().numpy()
    model.mem.write(writes["keys"].detach().reshape(-1, model.config.d_k).float().cpu(),
                    writes["codes"].detach().reshape(-1, model.config.pq_m).cpu().numpy(), tokens, tag)


@torch.no_grad()
def evaluate(model, tok, texts, device, L, B=8, max_windows=64):
    model.eval()
    wins = []
    for w in _pack(tok, texts, L):
        wins.append(w)
        if len(wins) >= max_windows:
            break
    if not wins:
        return float("nan"), float("nan")
    res = {True: [], False: []}
    for use in (True, False):
        for i in range(0, len(wins), B):
            ids = torch.from_numpy(np.stack(wins[i:i + B])).to(device)
            res[use].append(model(ids, labels=ids, use_store=use, reduction="none").loss.cpu())
    on, off = torch.cat(res[True]).mean().item(), torch.cat(res[False]).mean().item()
    return on, off


def train(model, tok, make_rows, held, a, device):
    os.makedirs(a.out, exist_ok=True)
    model.to(device).train()
    opts = build_optimizers(model, a.lr_muon, a.lr_adam)
    base_lrs = [[g["lr"] for g in o.param_groups] for o in opts]
    amp = device.type == "cuda"
    scaler = torch.amp.GradScaler("cuda", enabled=amp)
    state = {"step": 0, "windows": 0, "elapsed": 0.0}
    sp = os.path.join(a.out, "trainer_state.pt")
    if a.resume and os.path.exists(sp):
        st = torch.load(sp, map_location="cpu", weights_only=False)
        for o, s in zip(opts, st["opts"]):
            o.load_state_dict(s)
        scaler.load_state_dict(st["scaler"])
        torch.set_rng_state(st["rng"])
        state = st["state"]
        print(f"[resume] step {state['step']} windows {state['windows']} elapsed {state['elapsed']:.0f}s", flush=True)
    hub = HubSync(a.hub_repo) if a.hub_repo else None
    stream = window_stream(tok, make_rows, a.seq_len, skip=state["windows"])
    t_start, last_ck, tok_count, t_log = time.time() - state["elapsed"], time.time(), 0, time.time()
    stage = os.path.join(a.out, "hub_stage")

    def checkpoint_now(final=False):
        state["elapsed"] = time.time() - t_start
        if hub and not final and (hub.busy.is_set() or hub.q.full()):
            return
        save_bundle(stage, model, tok)
        torch.save({"opts": [o.state_dict() for o in opts], "scaler": scaler.state_dict(), "rng": torch.get_rng_state(),
                    "state": dict(state)}, os.path.join(stage, "trainer_state.pt"))
        shutil.copy(os.path.join(stage, "trainer_state.pt"), sp)
        if hub:
            if final:
                hub.flush()
                hub.push(stage, f"final step {state['step']}")
                hub.flush()
            else:
                hub.push(stage, f"checkpoint step {state['step']}")

    while True:
        elapsed = time.time() - t_start
        prog = elapsed / (a.minutes * 60) if a.minutes else state["step"] / max(1, a.max_steps)
        if prog >= 1 or (a.max_steps and state["step"] >= a.max_steps):
            break
        try:
            batch = np.stack([next(stream) for _ in range(a.batch)])
        except StopIteration:
            break
        ids = torch.from_numpy(batch).to(device)
        m = lr_mult(prog)
        for o, bl in zip(opts, base_lrs):
            for g, b in zip(o.param_groups, bl):
                g["lr"] = b * m
        with torch.autocast(device_type=device.type, dtype=torch.float16, enabled=amp):
            out = model(ids, labels=ids)
        scaler.scale(out.loss).backward()
        for o in opts:
            scaler.unscale_(o)
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        for o in opts:
            scaler.step(o)
        scaler.update()
        for o in opts:
            o.zero_grad(set_to_none=True)
        with torch.no_grad():
            write_batch(model, ids, a.tag)
        state["step"] += 1
        state["windows"] += a.batch
        tok_count += ids.numel()
        if state["step"] % a.dead_every == 0:
            dead = model.writer.reinit_dead()
            if dead:
                print(f"[codebook] reinitialised {dead} dead codes", flush=True)
        if state["step"] % a.log_every == 0:
            aux = {k: round(float(v), 4) for k, v in model.last_aux.items()}
            print(f"step {state['step']:5d} loss {float(out.loss.detach()):.4f} {aux} lr x{m:.2f} "
                  f"{tok_count / (time.time() - t_log):.0f} tok/s store {model.mem.store.n} index {model.mem.index.n} "
                  f"elapsed {time.time() - t_start:.0f}s", flush=True)
            tok_count, t_log = 0, time.time()
        if a.ckpt_minutes and time.time() - last_ck > a.ckpt_minutes * 60:
            checkpoint_now()
            last_ck = time.time()
    checkpoint_now(final=True)
    if held:
        on, off = evaluate(model, tok, held, device, a.seq_len)
        print(f"[heldout] loss with barameters {on:.4f} | store disabled {off:.4f}", flush=True)
    model.train()
    return state


