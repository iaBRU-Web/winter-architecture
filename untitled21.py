@torch.no_grad()
def window_ids(mem, w, per, device):
    return torch.from_numpy(mem.index.window(w, per).astype(np.int64))[None].to(device)


@torch.no_grad()
def reencode_windows(model, windows, device, per, tag_ds=None):
    """Re-encode index windows with the current writer; refreshes index keys and existing store slots."""
    mem, C = model.mem, model.config.write_chunk
    for w in windows:
        ids = window_ids(mem, w, per, device)
        wr = model.encode_chunks(ids)
        if wr is None:
            continue
        rows = np.arange(w * per, w * per + wr["keys"].shape[1])
        k = wr["keys"][0].float().cpu().numpy().astype(np.float16)
        mem.index.keys.buf[rows] = k
        mem.index.invalidate()
        slots = np.nonzero(np.isin(mem.store.chunk.data, rows))[0]
        if len(slots):
            pos = {int(r): i for i, r in enumerate(rows)}
            for s in slots:
                i = pos[int(mem.store.chunk.data[s])]
                mem.store.keys.buf[s] = k[i]
                mem.store.codes.buf[s] = wr["codes"][0, i].cpu().numpy().astype(np.uint8)
    mem.store.invalidate()


@torch.no_grad()
def reindex(model, device, seq_len):
    per = seq_len // model.config.write_chunk
    nw = math.ceil(model.mem.index.n / per)
    reencode_windows(model, range(nw), device, per)
    return nw


@torch.no_grad()
def deep_search(model, tok, text, device, topm=3):
    """Encode the query as one chunk, brute-force search the full ChunkIndex. Returns [(score,row,text)]."""
    mem = model.mem
    ids = torch.tensor([tok.encode(text)], device=device)
    wr = model.encode_chunks(ids, chunk=ids.shape[1])
    if wr is None or mem.index.n == 0:
        return []
    sc, ix = mem.index.search(wr["keys"][0].float(), topm)
    return [(float(s), int(i), tok.decode(mem.index.tok.data[int(i)])) for s, i in zip(sc[0], ix[0])]


@torch.no_grad()
def answer(model, tok, question, device, deep=False, score_thr=0.5, ent_thr=4.0, topm=3, expand=2, max_new=128, temperature=0.7):
    model.eval()
    mem = model.mem
    prompt = tok.encode(f"<|user|>\n{question}\n<|assistant|>\n")
    pid = torch.tensor([prompt], device=device)
    info = {"deep": False, "best_score": None, "entropy": None, "hits": []}
    p = torch.softmax(model(pid).logits[0, -1].float(), -1)
    info["entropy"] = float(-(p * torch.log(p + 1e-9)).sum())
    wr = model.encode_chunks(pid, chunk=pid.shape[1])
    if wr is not None and mem.store.n:
        info["best_score"] = float(mem.store.search(wr["keys"][0].float(), 1)[0][0, 0])
    if deep or info["best_score"] is None or info["best_score"] < score_thr or info["entropy"] > ent_thr:
        hits = deep_search(model, tok, question, device, topm)
        info["deep"], info["hits"] = True, hits
        ctx = []
        for _, row, _ in hits:
            ctx += [int(t) for r in range(row, min(row + 1 + expand, mem.index.n)) for t in mem.index.tok.data[r]]
        prompt = (ctx + prompt)[-(model.config.max_seq_len - max_new):]
        pid = torch.tensor([prompt], device=device)
    out = model.chat_generate(pid, max_new=max_new, temperature=temperature)[0, len(prompt):]
    return tok.decode(out).replace("<eos>", "").strip(), info


@torch.no_grad()
def forgetting_scan(model, device, seq_len, n_windows=128, B=8):
    mem = model.mem
    per = seq_len // model.config.write_chunk
    nw = mem.index.n // per
    if nw == 0:
        return []
    model.eval()
    pick = random.sample(range(nw), min(n_windows, nw))
    res = []
    for i in range(0, len(pick), B):
        ws = pick[i:i + B]
        ids = torch.cat([window_ids(mem, w, per, device) for w in ws])
        off = model(ids, labels=ids, use_store=False, reduction="none").loss.cpu()
        on = model(ids, labels=ids, use_store=True, reduction="none").loss.cpu()
        res += [(float(o), float(n), w) for o, n, w in zip(off, on, ws)]
    return sorted(res, reverse=True)  # worst (store-off loss highest) first


def refresh(model, device, seq_len, steps=20, worst=32, replay=32, lr=3e-5, B=8, scan=128):
    mem, per = model.mem, seq_len // model.config.write_chunk
    scanned = forgetting_scan(model, device, seq_len, scan, B)
    if not scanned:
        return {"scanned": 0}
    bad = [w for _, _, w in scanned[:worst]]
    rest = [w for _, _, w in scanned[worst:]] or bad
    before = sum(s[0] for s in scanned[:worst]) / len(bad)
    opt = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=0.0)
    model.train()
    for _ in range(steps):  # half worst, half replay so repairing one thing does not erase another
        ws = random.sample(bad, min(B // 2, len(bad))) + random.sample(rest, min(B - B // 2, len(rest)))
        ids = torch.cat([window_ids(mem, w, per, device) for w in ws])
        loss = model(ids, labels=ids, use_store=False).loss
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        opt.step(); opt.zero_grad(set_to_none=True)
    model.eval()
    reencode_windows(model, bad, device, per)  # rewrite barameters for the repaired chunks (fixes key drift too)
    with torch.no_grad():
        after = sum(float(model(torch.cat([window_ids(mem, w, per, device) for w in bad[i:i + B]]), labels=torch.cat(
            [window_ids(mem, w, per, device) for w in bad[i:i + B]]), use_store=False, reduction="none").loss.sum())
                    for i in range(0, len(bad), B)) / len(bad)
    return {"scanned": len(scanned), "repaired": len(bad), "loss_before": before, "loss_after": after}


