class BarameterWriter(nn.Module):
    """Text chunk -> (key, PQ-coded value). Attention-pool hidden states, project, product-quantise (straight-through)."""

    def __init__(self, cfg):
        super().__init__()
        D, m = cfg.d_model, cfg.pq_m
        self.m, self.K, self.ds_, self.dk, self.dv = m, cfg.pq_k, cfg.d_v // m, cfg.d_k, cfg.d_v
        self.norm = RMSNorm(D)
        self.pool_q = nn.Parameter(torch.randn(D) * 0.02)
        self.wk, self.wv = nn.Linear(D, cfg.d_k, bias=False), nn.Linear(D, cfg.d_v, bias=False)
        self.codebook = nn.Parameter(torch.randn(m, cfg.pq_k, self.ds_) * 0.5)
        self.register_buffer("usage", torch.zeros(m, cfg.pq_k))
        self.last_vs = None

    def forward(self, h, C):
        B, L, D = h.shape
        nc = L // C
        if nc == 0:
            return None
        hh = self.norm(h[:, : nc * C]).float().view(B, nc, C, D)
        a = torch.softmax((hh * self.pool_q.float()).sum(-1) * 0.125, -1)  # fixed temperature: independent of d_model (growth-safe)
        pooled = (a.unsqueeze(-1) * hh).sum(2)
        with torch.autocast(device_type=h.device.type, enabled=False):
            key = F.normalize(self.wk(pooled), dim=-1)
            vs = self.wv(pooled).view(B, nc, self.m, self.ds_)
            cb = self.codebook.float()
            dist = (vs ** 2).sum(-1, keepdim=True) - 2 * torch.einsum("bcmd,mkd->bcmk", vs, cb) + (cb ** 2).sum(-1)
            codes = dist.argmin(-1)  # B,nc,m
            qv = cb[torch.arange(self.m, device=h.device), codes]  # B,nc,m,ds
            commit = 0.25 * F.mse_loss(vs, qv.detach()) + F.mse_loss(qv, vs.detach())
            vq = (vs + (qv - vs).detach()).reshape(B, nc, self.dv)
        div = key.reshape(-1, self.dk).mean(0).pow(2).sum()
        if self.training:
            with torch.no_grad():
                self.usage += F.one_hot(codes, self.K).sum((0, 1)).float()
                self.last_vs = vs.detach().reshape(-1, self.m, self.ds_)[:4096]
        return {"keys": key, "vals": vq, "codes": codes, "aux": {"commit": commit, "div": div}}

    @torch.no_grad()
    def reinit_dead(self):
        if self.last_vs is None:
            return 0
        n = 0
        for mi in range(self.m):
            dead = (self.usage[mi] == 0).nonzero().flatten()
            if len(dead):
                pick = self.last_vs[torch.randint(len(self.last_vs), (len(dead),), device=self.last_vs.device), mi]
                self.codebook.data[mi, dead] = pick + 0.01 * torch.randn_like(pick)
                n += len(dead)
        self.usage.zero_()
        return n


class BarameterRead(nn.Module):
    """x += sigmoid(gate) * Wo( softmax(top-k persistent slots + causal in-sequence chunks) . values ). Starts ~off."""

    def __init__(self, cfg):
        super().__init__()
        D = cfg.d_model
        self.cfg = cfg
        self.norm = RMSNorm(D)
        self.wq = nn.Linear(D, cfg.d_k, bias=False)
        self.gate = nn.Linear(D, 1)
        self.wo = nn.Linear(cfg.d_v, D, bias=False)
        self.log_scale = nn.Parameter(torch.tensor(math.log(10.0)))
        nn.init.constant_(self.gate.bias, -4.0)

    def forward(self, x, mem, codebook, local, use_store):
        cfg = self.cfg
        B, L, _ = x.shape
        h = self.norm(x)
        q = F.normalize(self.wq(h).float(), dim=-1)
        scale = self.log_scale.exp().clamp(max=64.0)
        parts, sp, vp = [], None, None
        if use_store and mem.store.n > 0:
            qf = q.reshape(B * L, -1)
            with torch.no_grad():
                _, idx = mem.store.search(qf.detach(), cfg.topk)
            kk = mem.store.gather_keys(idx, x.device)
            sp = (scale * (qf.unsqueeze(1) * kk).sum(-1)).view(B, L, -1)
            vp = mem.store.dequant(idx, codebook).float().view(B, L, idx.shape[1], -1)
            parts.append(sp)
        if local is not None:
            lk, C = local["keys"], cfg.write_chunk
            nc = lk.shape[1]
            sl = scale * torch.einsum("bld,bcd->blc", q, lk)
            valid = (torch.arange(L, device=x.device) // C)[:, None] > torch.arange(nc, device=x.device)[None]
            parts.append(sl.masked_fill(~valid[None], -1e4))
        if not parts:
            return x, q
        allsc = torch.cat(parts, -1)
        w = torch.softmax(allsc, -1) * (allsc > -1e3)
        r, off = 0, 0
        if sp is not None:
            kp = sp.shape[-1]
            r = r + torch.einsum("blk,blkd->bld", w[..., :kp], vp)
            off = kp
        if local is not None:
            r = r + torch.einsum("blc,bcd->bld", w[..., off:], local["vals"].float())
        out = torch.sigmoid(self.gate(h).float()) * self.wo(r.to(h.dtype)).float()
        return x + out.to(x.dtype), q


