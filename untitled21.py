class RMSNorm(nn.Module):
    def __init__(self, d, eps=1e-8):
        super().__init__()
        self.weight, self.eps = nn.Parameter(torch.ones(d)), eps

    def forward(self, x):
        xf = x.float()
        return (xf * torch.rsqrt(xf.pow(2).mean(-1, keepdim=True) + self.eps)).to(x.dtype) * self.weight


def rope(x, theta):  # x: (B,H,L,Dh)
    half = x.shape[-1] // 2
    freqs = 1.0 / (theta ** (torch.arange(half, device=x.device, dtype=torch.float32) / half))
    ang = torch.arange(x.shape[2], device=x.device, dtype=torch.float32)[:, None] * freqs[None]
    cos, sin = ang.cos(), ang.sin()
    x1, x2 = x[..., :half].float(), x[..., half:].float()
    return torch.cat([x1 * cos - x2 * sin, x1 * sin + x2 * cos], -1).to(x.dtype)


class SwiGLU(nn.Module):
    def __init__(self, d, h):
        super().__init__()
        self.w1, self.w3, self.w2 = nn.Linear(d, h, bias=False), nn.Linear(d, h, bias=False), nn.Linear(h, d, bias=False)

    def forward(self, x):
        return self.w2(F.silu(self.w1(x)) * self.w3(x))


def chunked_gated_linear_attention(q, k, v, g, chunk):
    """q,k,v: (B,L,H,dh) float32 (q,k L2-normalised); g: (B,L,H) log-decay <= 0.  Returns (B,L,H,dh).
    Within a chunk: decay-masked matmul.  Between chunks: carried state S (B,H,dh,dh).  All in fp32, log-space decay."""
    B, L, H, dh = q.shape
    pad = (-L) % chunk
    if pad:
        q, k, v = [F.pad(t, (0, 0, 0, 0, 0, pad)) for t in (q, k, v)]
        g = F.pad(g, (0, 0, 0, pad))
    Lp = L + pad
    nc = Lp // chunk
    q, k, v = [t.reshape(B, nc, chunk, H, dh).permute(0, 3, 1, 2, 4) for t in (q, k, v)]  # B,H,nc,C,dh
    g = g.reshape(B, nc, chunk, H).permute(0, 3, 1, 2)  # B,H,nc,C
    b = g.cumsum(-1)
    mask = torch.tril(torch.ones(chunk, chunk, dtype=torch.bool, device=q.device))
    diff = (b.unsqueeze(-1) - b.unsqueeze(-2)).masked_fill(~mask, float("-inf"))
    intra = torch.matmul(torch.matmul(q, k.transpose(-1, -2)) * torch.exp(diff), v)
    qd = q * torch.exp(b).unsqueeze(-1)
    kd = k * torch.exp(b[..., -1:] - b).unsqueeze(-1)
    total = torch.exp(b[..., -1])
    S = q.new_zeros(B, H, dh, dh)
    outs = []
    for c in range(nc):
        outs.append(torch.matmul(qd[:, :, c], S))
        S = S * total[:, :, c, None, None] + torch.matmul(kd[:, :, c].transpose(-1, -2), v[:, :, c])
    o = intra + torch.stack(outs, 2)  # B,H,nc,C,dh
    return o.permute(0, 2, 3, 1, 4).reshape(B, Lp, H, dh)[:, :L]


def reference_recurrence(q, k, v, g):
    B, L, H, dh = q.shape
    S = q.new_zeros(B, H, dh, dh)
    out = []
    for t in range(L):
        S = torch.exp(g[:, t])[..., None, None] * S + k[:, t].unsqueeze(-1) * v[:, t].unsqueeze(-2)
        out.append(torch.einsum("bhd,bhde->bhe", q[:, t], S))
    return torch.stack(out, 1)


class LinearRecurrentMix(nn.Module):
    def __init__(self, cfg):
        super().__init__()
        D, H, dh = cfg.d_model, cfg.n_heads, cfg.head_dim
        self.H, self.dh, self.chunk = H, dh, cfg.rec_chunk
        self.q, self.k, self.v = (nn.Linear(D, H * dh, bias=False) for _ in range(3))
        self.g = nn.Linear(D, H)
        self.o_gate = nn.Linear(D, H * dh, bias=False)
        self.onorm = RMSNorm(dh)
        self.out = nn.Linear(H * dh, D, bias=False)

    def forward(self, x):
        B, L, _ = x.shape
        H, dh = self.H, self.dh
        og = torch.sigmoid(self.o_gate(x)).view(B, L, H, dh)
        with torch.autocast(device_type=x.device.type, enabled=False):
            q = F.normalize(self.q(x).float().view(B, L, H, dh), dim=-1)
            k = F.normalize(self.k(x).float().view(B, L, H, dh), dim=-1)
            v = self.v(x).float().view(B, L, H, dh)
            g = -F.softplus(self.g(x).float())
            o = chunked_gated_linear_attention(q, k, v, g, self.chunk)
        o = self.onorm(o.to(x.dtype)) * og
        return self.out(o.reshape(B, L, H * dh))


class CausalAttention(nn.Module):
    def __init__(self, cfg):
        super().__init__()
        D, H, Hkv, dh = cfg.d_model, cfg.n_heads, cfg.n_kv_heads, cfg.head_dim
        self.H, self.Hkv, self.dh, self.theta = H, Hkv, dh, cfg.rope_theta
        self.q = nn.Linear(D, H * dh, bias=False)
        self.k = nn.Linear(D, Hkv * dh, bias=False)
        self.v = nn.Linear(D, Hkv * dh, bias=False)
        self.out = nn.Linear(H * dh, D, bias=False)
        self.qn, self.kn = RMSNorm(dh), RMSNorm(dh)

    def forward(self, x):
        B, L, _ = x.shape
        q = self.qn(self.q(x).view(B, L, self.H, self.dh)).transpose(1, 2)
        k = self.kn(self.k(x).view(B, L, self.Hkv, self.dh)).transpose(1, 2)
        v = self.v(x).view(B, L, self.Hkv, self.dh).transpose(1, 2)
        q, k = rope(q, self.theta), rope(k, self.theta)
        g = self.H // self.Hkv
        k, v = k.repeat_interleave(g, 1), v.repeat_interleave(g, 1)
        o = F.scaled_dot_product_attention(q, k, v, is_causal=True)
        return self.out(o.transpose(1, 2).reshape(B, L, self.H * self.dh))


class Block(nn.Module):
    def __init__(self, cfg, kind):
        super().__init__()
        self.kind = kind
        self.n1, self.n2 = RMSNorm(cfg.d_model), RMSNorm(cfg.d_model)
        self.mix = CausalAttention(cfg) if kind == "attn" else LinearRecurrentMix(cfg)
        self.ffn = SwiGLU(cfg.d_model, cfg.ffn_hidden)

    def forward(self, x):
        x = x + self.mix(self.n1(x))
        return x + self.ffn(self.n2(x))


