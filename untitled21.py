def selftest():
    torch.manual_seed(0); random.seed(0); np.random.seed(0)
    dev = torch.device("cpu")
    ok = lambda name: print(f"  PASS  {name}", flush=True)
    # 0. default-size parameter count
    big = BarameterForCausalLM(BarameterConfig())
    print(f"  default config params: {big.num_params() / 1e6:.1f}M (vocab 16k)")
    del big
    # 1. recurrence correctness
    q, k = F.normalize(torch.randn(2, 37, 3, 16), dim=-1), F.normalize(torch.randn(2, 37, 3, 16), dim=-1)
    v, g = torch.randn(2, 37, 3, 16), -F.softplus(torch.randn(2, 37, 3))
    err = (chunked_gated_linear_attention(q, k, v, g, 8) - reference_recurrence(q, k, v, g)).abs().max().item()
    assert err < 1e-4, err
    ok(f"chunked recurrence == sequential reference (max err {err:.2e})")
    # data
    caps = {f"Land{i}": f"City{(i * 7) % 50}" for i in range(120)}
    rows = [f"<|user|>\nWhat is the capital of {c}?\n<|assistant|>\nThe capital of {c} is {v}." for c, v in caps.items()]
    held, trainrows = rows[:10], rows[10:]
    tok = Tok.train(rows, 400)
    cfg = BarameterConfig(vocab_size=tok.vocab_size, d_model=128, n_heads=4, n_kv_heads=2, head_dim=32, ffn_hidden=192,
                          block_types=["lin", "lin", "attn", "lin", "lin", "attn"], read_after=[2, 4], write_from=3,
                          rec_chunk=16, write_chunk=8, max_seq_len=64, store_slots=300, d_k=32, d_v=64, pq_m=4, pq_k=16, topk=4)
    model = BarameterForCausalLM(cfg)
    ids = torch.randint(4, cfg.vocab_size, (2, 64))
    model.train()
    out = model(ids, labels=ids)
    out.loss.backward()
    assert torch.isfinite(out.loss) and all(torch.isfinite(p.grad).all() for p in model.parameters() if p.grad is not None)
    ok(f"forward/backward finite (loss {out.loss.item():.3f}, ln V = {math.log(cfg.vocab_size):.3f}, aux {sorted(model.last_aux)})")
    model.zero_grad()
    # 2. training loop with barameter writes
    tmp = tempfile.mkdtemp()
    a = argparse.Namespace(out=tmp, hub_repo=None, minutes=0, max_steps=80, batch=8, seq_len=64, lr_muon=0.02, lr_adam=2e-3,
                           ckpt_minutes=0, tag="capitals", log_every=20, dead_every=40, resume=False)
    make_rows = lambda ep: iter(random.Random(ep).sample(trainrows, len(trainrows)))
    st = train(model, tok, make_rows, held, a, dev)
    assert st["step"] == 80 and model.mem.store.n > 0 and model.mem.index.n > 0 and model.mem.store.n <= cfg.store_slots
    ok(f"train loop: store {model.mem.store.n}/{cfg.store_slots} slots, index {model.mem.index.n} chunks")
    # 3. generate + deep search + answer
    s_, i_ = answer(model, tok, "What is the capital of Land3?", dev, deep=True, max_new=12)
    assert i_["deep"] and len(i_["hits"]) > 0
    ok(f"answer() with deep search ran ({len(i_['hits'])} hits)")
    # 4. forgetting scan + refresh
    r = refresh(model, dev, 64, steps=3, worst=4, scan=8, B=4)
    assert r["scanned"] > 0
    ok(f"refresh ran: {r}")
    nw = reindex(model, dev, 64)
    ok(f"reindex re-encoded {nw} windows")
    # 5. growth is function-preserving
    model.eval()
    base = model(ids).logits
    grown = grow_model(model, add_layers=2, new_d_model=256).eval()
    diff = (grown(ids).logits - base).abs().max().item()
    assert diff < 1e-3, diff
    ok(f"grow {model.num_params() / 1e6:.2f}M -> {grown.num_params() / 1e6:.2f}M params ({cfg.n_layers}->{grown.config.n_layers} layers, "
       f"d {cfg.d_model}->{grown.config.d_model}); max logit diff {diff:.2e}")
    gl = grown.train()(ids, labels=ids)
    gl.loss.backward()
    ok("grown model trains (backward finite)")
    # 6. save / load roundtrip
    save_bundle(tmp + "/ck", grown.eval(), tok)
    m2, t2, _ = load_bundle(tmp + "/ck", dev)
    assert (m2.eval()(ids).logits - grown(ids).logits).abs().max().item() < 1e-5 and m2.mem.store.n == grown.mem.store.n
    ok("save_bundle/load_bundle roundtrip (weights + store + index)")
    try:
        m3 = AutoModelForCausalLM.from_pretrained(tmp + "/ck")
        ok("AutoModelForCausalLM.from_pretrained on the saved folder")
    except Exception as e:
        print(f"  WARN  AutoModelForCausalLM.from_pretrained failed: {e}")
    m4 = AutoModelForCausalLM.from_config(cfg)
    assert isinstance(m4, BarameterForCausalLM)
    ok("AutoClass registration (AutoModelForCausalLM.from_config)")
    # 7. delete a dataset -> forgotten
    n0 = model.mem.store.n
    ns, ni = model.mem.delete("capitals")
    assert model.mem.store.n == 0 and model.mem.index.n == 0 and ns == n0
    ok(f"delete dataset tag: removed {ns} barameters and {ni} chunks")
    print("ALL SELF-TESTS PASSED")


