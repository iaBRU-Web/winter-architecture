# Optimiser (Muon for 2-D hidden weights, AdamW for the rest)
# ----------------------------------------------------------------------------------------------
def newton_schulz(G, steps=5):
    a, b, c = 3.4445, -4.7750, 2.0315
    X = G.float()
    X = X / (X.norm() + 1e-7)
    tr = X.shape[0] > X.shape[1]
    if tr:
        X = X.T
    for _ in range(steps):
        A = X @ X.T
        X = a * X + (b * A + c * A @ A) @ X
    return X.T if tr else X


class Muon(torch.optim.Optimizer):
    def __init__(self, params, lr=0.02, momentum=0.95, wd=0.01):
        super().__init__(params, dict(lr=lr, momentum=momentum, wd=wd))

    @torch.no_grad()
    def step(self, closure=None):
        for g in self.param_groups:
            for p in g["params"]:
                if p.grad is None:
                    continue
                st = self.state[p]
                if "buf" not in st:
                    st["buf"] = torch.zeros_like(p)
                st["buf"].mul_(g["momentum"]).add_(p.grad)
                u = newton_schulz(p.grad.add(st["buf"], alpha=g["momentum"]))
                u = u * max(1.0, p.shape[0] / p.shape[1]) ** 0.5
                p.mul_(1 - g["lr"] * g["wd"]).add_(u.to(p.dtype), alpha=-g["lr"])


def build_optimizers(model, lr_muon, lr_adam, wd=0.01):
    mu, ad = [], []
    for n, p in model.named_parameters():
        (mu if p.ndim == 2 and "embed" not in n else ad).append(p)
    return [Muon(mu, lr=lr_muon, wd=wd), torch.optim.AdamW(ad, lr=lr_adam, betas=(0.9, 0.95), weight_decay=0.0)]


def lr_mult(prog, warm=0.03):
    if prog < warm:
        return max(prog / warm, 0.02)
    return 0.1 + 0.9 * 0.5 * (1 + math.cos(math.pi * min(1.0, (prog - warm) / (1 - warm))))


