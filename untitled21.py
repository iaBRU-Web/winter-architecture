class BarameterForCausalLM(PreTrainedModel):
    config_class = BarameterConfig
    base_model_prefix = "barameter"
    _tied_weights_keys = []

    def __init__(self, config):
        super().__init__(config)
        self.all_tied_weights_keys = {}
        cfg = config
        self.embed = nn.Embedding(cfg.vocab_size, cfg.d_model)
        self.blocks = nn.ModuleList([Block(cfg, t) for t in cfg.block_types])
        self.reads = nn.ModuleDict({str(n): BarameterRead(cfg) for n in cfg.read_after})
        self.writer = BarameterWriter(cfg)
        self.norm = RMSNorm(cfg.d_model)
        self.mem = Memory(cfg)
        self.last_writes, self.last_aux = None, {}
        self._init()

    def _init(self):
        std, out_std = 0.02, 0.02 / math.sqrt(2 * self.config.n_layers)
        for name, m in self.named_modules():
            if isinstance(m, nn.Linear):
                tail = name.split(".")[-1]
                nn.init.normal_(m.weight, 0, out_std if tail in ("out", "w2", "wo") else std)
                if m.bias is not None:
                    nn.init.zeros_(m.bias)
            elif isinstance(m, nn.Embedding):
                nn.init.normal_(m.weight, 0, std)
        for b in self.blocks:
            if b.kind == "lin":
                with torch.no_grad():
                    b.mix.g.bias.copy_(torch.linspace(-4.5, -1.0, b.mix.H))
        for n, r in self.reads.items():
            nn.init.constant_(r.gate.bias, -4.0)

    def get_input_embeddings(self):
        return self.embed

    def num_params(self):
        return sum(p.numel() for p in self.parameters())

    # ---- core ----
    def _run(self, ids, use_store=True, C=None, stop_at_write=False):
        cfg = self.config
        C = C or cfg.write_chunk
        x, writes, aux = self.embed(ids), None, {}
        for i, blk in enumerate(self.blocks):
            if cfg.grad_checkpoint and self.training and torch.is_grad_enabled():
                x = checkpoint(blk, x, use_reentrant=False)
            else:
                x = blk(x)
            n = i + 1
            if n == cfg.write_from:
                writes = self.writer(x, C)
                if writes is not None:
                    aux.update(writes["aux"])
                if stop_at_write:
                    return x, writes, aux
            if str(n) in self.reads:
                local = writes if (writes is not None and cfg.local_memory and n > cfg.write_from) else None
                rd = self.reads[str(n)]
                x, q = rd(x, self.mem, self.writer.codebook, local, use_store)
                if local is not None and self.training and local["keys"].shape[1] > 1:
                    nc, B = local["keys"].shape[1], ids.shape[0]
                    qm = F.normalize(q[:, : nc * C].reshape(B, nc, C, -1).mean(2), dim=-1)[:, 1:].reshape(B * (nc - 1), -1)
                    kt = local["keys"][:, :-1].reshape(B * (nc - 1), -1)
                    lg = rd.log_scale.exp().clamp(max=64.0) * qm @ kt.T
                    aux["contrast"] = F.cross_entropy(lg, torch.arange(len(lg), device=lg.device))
        return x, writes, aux

    def forward(self, input_ids, labels=None, use_store=True, reduction="mean", **kw):
        cfg = self.config
        x, writes, aux = self._run(input_ids, use_store)
        h = self.norm(x)
        logits = cfg.softcap * torch.tanh(F.linear(h, self.embed.weight.to(h.dtype)).float() / cfg.softcap)
        loss = None
        if labels is not None:
            lg, tg = logits[:, :-1], labels[:, 1:]
            ce = F.cross_entropy(lg.reshape(-1, lg.shape[-1]), tg.reshape(-1), ignore_index=-100, reduction="none").view(tg.shape)
            valid = (tg != -100).float()
            if reduction == "none":
                loss = (ce * valid).sum(1) / valid.sum(1).clamp(min=1)
            else:
                ce_m = (ce * valid).sum() / valid.sum().clamp(min=1)
                z = torch.logsumexp(lg, -1).pow(2).mean()
                loss = ce_m + 1e-4 * z + aux.get("commit", 0) + 0.1 * aux.get("contrast", 0) + 0.01 * aux.get("div", 0)
                self.last_aux = {"ce": ce_m.detach(), **{k: v.detach() for k, v in aux.items()}}
        self.last_writes = writes
        return CausalLMOutput(loss=loss, logits=logits)

    @torch.no_grad()
    def encode_chunks(self, ids, chunk=None):
        """Forward-only barameter writer (ingestion path). Returns dict(keys, codes) or None."""
        was = self.training
        self.eval()
        _, writes, _ = self._run(ids, True, chunk, stop_at_write=True)
        self.train(was)
        return writes

    @torch.no_grad()
    def chat_generate(self, ids, max_new=128, temperature=0.7, top_k=40, eos=1):
        self.eval()
        out = ids.clone()
        for _ in range(max_new):
            lg = self(out[:, -self.config.max_seq_len:]).logits[:, -1].float()
            if temperature <= 0:
                nxt = lg.argmax(-1, keepdim=True)
            else:
                lg = lg / temperature
                v, _ = lg.topk(min(top_k, lg.shape[-1]))
                lg = lg.masked_fill(lg < v[:, -1:], float("-inf"))
                nxt = torch.multinomial(torch.softmax(lg, -1), 1)
            out = torch.cat([out, nxt], 1)
            if int(nxt) == eos:
                break
        return out

    def load_memory(self, path_or_repo, mmap=False):
        d = resolve_path(path_or_repo)
        self.mem.load(os.path.join(d, "memory"), mmap)


