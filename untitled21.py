class GrowArray:
    """Append-only numpy array with doubling capacity; can be opened as a read-only memmap."""

    def __init__(self, tail, dtype, cap=1024):
        self.tail, self.dtype = tuple(tail), np.dtype(dtype)
        self.buf, self.n, self.ro = np.zeros((cap,) + self.tail, self.dtype), 0, False

    @property
    def data(self):
        return self.buf[: self.n]

    def append(self, arr):
        if self.ro:
            raise RuntimeError("memory opened read-only (--mmap); reload without --mmap to modify it")
        arr = np.asarray(arr, self.dtype)
        m, need = len(arr), self.n + len(arr)
        if need > len(self.buf):
            nb = np.zeros((max(need, 2 * len(self.buf)),) + self.tail, self.dtype)
            nb[: self.n] = self.buf[: self.n]
            self.buf = nb
        st = self.n
        self.buf[st:st + m] = arr
        self.n += m
        return st

    def keep(self, mask):
        d = np.array(self.buf[: self.n][mask])
        self.buf = np.concatenate([d, np.zeros((16,) + self.tail, self.dtype)])
        self.n, self.ro = len(d), False

    def save(self, path):
        np.save(path, np.ascontiguousarray(self.data))

    def load(self, path, mmap=False):
        a = np.load(path, mmap_mode="r" if mmap else None)
        self.buf, self.n, self.ro = (a, len(a), True) if mmap else (np.concatenate([a, np.zeros((16,) + self.tail, self.dtype)]), len(a), False)


def chunked_topk(keys, q, k, step=16384):
    """Brute-force top-k of q (Q,dk) against keys (N,dk) (torch or numpy/memmap), streaming over N."""
    N = len(keys)
    if N == 0:
        return q.new_zeros(len(q), 0), torch.zeros(len(q), 0, dtype=torch.long, device=q.device)
    best_s = best_i = None
    for a in range(0, N, step):
        kc = keys[a:a + step]
        if isinstance(kc, np.ndarray):
            kc = torch.from_numpy(np.ascontiguousarray(kc))
        sc = q @ kc.to(q.device).to(q.dtype).T
        s, i = sc.topk(min(k, sc.shape[1]), dim=1)
        i = i + a
        if best_s is None:
            best_s, best_i = s, i
        else:
            cs, ci = torch.cat([best_s, s], 1), torch.cat([best_i, i], 1)
            best_s, j = cs.topk(min(k, cs.shape[1]), 1)
            best_i = ci.gather(1, j)
    return best_s.float(), best_i


def hash_rows(tokens):
    return np.array([int.from_bytes(hashlib.blake2b(np.ascontiguousarray(r).tobytes(), digest_size=8).digest(), "little", signed=True)
                     for r in tokens], np.int64)


class _KeyedArrays:
    """Shared helpers: GPU key cache and sorted-hash lookup."""
    _cache = None
    _hs = None

    def _qdtype(self, q):
        return q.half() if q.is_cuda else q.float()

    def keys_for(self, device):
        if device.type == "cuda" and self.keys.n * self.keys.tail[0] * 2 < 1.5e9:
            if self._cache is None or len(self._cache) != self.keys.n:
                self._cache = torch.from_numpy(np.ascontiguousarray(self.keys.data)).to(device)
            return self._cache
        return self.keys.data

    def search(self, q, k):
        return chunked_topk(self.keys_for(q.device), self._qdtype(q), k)

    def lookup(self, h):
        if self._hs is None:
            order = np.argsort(self.hash.data, kind="stable")
            self._hs, self._ho = self.hash.data[order], order
        if len(self._hs) == 0:
            return np.zeros(len(h), np.int64), np.zeros(len(h), bool)
        pos = np.minimum(np.searchsorted(self._hs, h), len(self._hs) - 1)
        return self._ho[pos], self._hs[pos] == h

    def invalidate(self, hashes_changed=False):
        self._cache = None
        if hashes_changed:
            self._hs = None


class ChunkIndex(_KeyedArrays):
    """Cold tier: every chunk ever seen (key + tokens). Never evicts; used by the deep search path."""

    def __init__(self, cfg):
        self.keys = GrowArray((cfg.d_k,), np.float16)
        self.tok = GrowArray((cfg.write_chunk,), np.int32)
        self.ds = GrowArray((), np.int32)
        self.hash = GrowArray((), np.int64)

    @property
    def n(self):
        return self.keys.n

    def add(self, keys, tokens, ds):
        tokens = np.ascontiguousarray(tokens, np.int32)
        h, keys = hash_rows(tokens), np.asarray(keys, np.float16)
        slot, hit = self.lookup(h)
        rows = np.zeros(len(h), np.int64)
        rows[hit] = slot[hit]
        self.keys.buf[rows[hit]] = keys[hit]  # refresh with the newest key
        new = ~hit
        if new.any():
            st = self.keys.append(keys[new])
            self.tok.append(tokens[new]); self.ds.append(np.full(int(new.sum()), ds, np.int32)); self.hash.append(h[new])
            rows[new] = np.arange(st, st + int(new.sum()))
            self.invalidate(True)
        else:
            self.invalidate()
        return rows, h

    def delete_ds(self, ds):
        mask = self.ds.data != ds
        remap = np.where(mask, np.cumsum(mask) - 1, -1).astype(np.int64)
        for a in (self.keys, self.tok, self.ds, self.hash):
            a.keep(mask)
        self.invalidate(True)
        return int((~mask).sum()), remap

    def window(self, w, per):
        return self.tok.data[w * per:(w + 1) * per].reshape(-1)

    def arrays(self):
        return {"keys": self.keys, "tok": self.tok, "ds": self.ds, "hash": self.hash}


class BarameterStore(_KeyedArrays):
    """Hot tier: fixed-capacity slots. key (L2-normalised fp16) + 4x8-bit PQ codes + metadata."""

    def __init__(self, cfg):
        self.cfg, self.cap, self.clock = cfg, cfg.store_slots, 0
        self.keys = GrowArray((cfg.d_k,), np.float16, 4096)
        self.codes = GrowArray((cfg.pq_m,), np.uint8, 4096)
        self.ds = GrowArray((), np.int32, 4096)
        self.usage = GrowArray((), np.int32, 4096)
        self.step = GrowArray((), np.int64, 4096)
        self.chunk = GrowArray((), np.int64, 4096)  # row in ChunkIndex (source text pointer)
        self.hash = GrowArray((), np.int64, 4096)
        self._codes_cache = None

    @property
    def n(self):
        return self.keys.n

    def arrays(self):
        return {"keys": self.keys, "codes": self.codes, "ds": self.ds, "usage": self.usage, "step": self.step,
                "chunk": self.chunk, "hash": self.hash}

    def invalidate(self, hashes_changed=False):
        super().invalidate(hashes_changed)
        self._codes_cache = None

    def _keep(self, mask):
        for a in self.arrays().values():
            a.keep(mask)
        self.invalidate(True)

    def gather_keys(self, idx, device):
        kf = self.keys_for(device)
        if isinstance(kf, torch.Tensor):
            return kf[idx].float()
        flat = np.asarray(kf[idx.cpu().numpy().reshape(-1)])
        return torch.from_numpy(flat).to(device).float().view(*idx.shape, -1)

    def dequant(self, idx, codebook):
        if self._codes_cache is None or len(self._codes_cache) != self.n or self._codes_cache.device != idx.device:
            self._codes_cache = torch.from_numpy(np.ascontiguousarray(self.codes.data)).to(idx.device)
        c = self._codes_cache[idx].long()  # (...,m)
        ar = torch.arange(c.shape[-1], device=idx.device)
        return codebook[ar, c].reshape(*idx.shape, -1)

    def write(self, keys, codes, ds, rows, hashes):
        keys = F.normalize(torch.as_tensor(keys).float(), dim=-1)
        k16 = keys.numpy().astype(np.float16)
        codes = np.asarray(codes, np.uint8)
        self.clock += 1
        slot, hit = self.lookup(hashes)
        for i in np.nonzero(hit)[0]:  # same chunk again: refresh in place
            j = slot[i]
            self.keys.buf[j], self.codes.buf[j] = k16[i], codes[i]
            self.usage.buf[j] += 1
            self.step.buf[j] = self.clock
        todo = np.nonzero(~hit)[0]
        if len(todo) and self.n > 0:  # near-duplicate merge
            sc, ix = self.search(keys[todo], 1)
            sims, ix = sc[:, 0].cpu().numpy(), ix[:, 0].cpu().numpy()
            merge = sims >= self.cfg.dedup_threshold
            for t, j in zip(todo[merge], ix[merge]):
                nk = 0.9 * self.keys.buf[j].astype(np.float32) + 0.1 * keys[t].numpy()
                self.keys.buf[j] = (nk / (np.linalg.norm(nk) + 1e-8)).astype(np.float16)
                self.usage.buf[j] += 1
                self.step.buf[j] = self.clock
            todo = todo[~merge]
        if len(todo):
            todo = todo[-self.cap:]
            need = len(todo) - (self.cap - self.n)
            if need > 0:  # evict least-used, then oldest
                order = np.lexsort((self.step.data, self.usage.data))[:need]
                mask = np.ones(self.n, bool)
                mask[order] = False
                self._keep(mask)
            m = len(todo)
            self.keys.append(k16[todo]); self.codes.append(codes[todo]); self.ds.append(np.full(m, ds, np.int32))
            self.usage.append(np.ones(m, np.int32)); self.step.append(np.full(m, self.clock, np.int64))
            self.chunk.append(rows[todo]); self.hash.append(hashes[todo])
        self.invalidate(True)

    def delete_ds(self, ds):
        mask = self.ds.data != ds
        n = int((~mask).sum())
        if n:
            self._keep(mask)
        return n

    def remap_chunks(self, remap):
        c = self.chunk.data
        ok = c >= 0
        self.chunk.buf[: self.n][ok] = remap[c[ok]]
        gone = self.chunk.data < 0
        if gone.any():
            self._keep(~gone)

    def clear(self):
        self._keep(np.zeros(self.n, bool))


class Memory:
    """Hot store + cold index + dataset tag registry. Lives on the model as model.mem (not an nn.Module)."""

    def __init__(self, cfg):
        self.cfg, self.datasets = cfg, []
        self.store, self.index = BarameterStore(cfg), ChunkIndex(cfg)

    def ds_id(self, tag):
        if tag not in self.datasets:
            self.datasets.append(tag)
        return self.datasets.index(tag)

    def write(self, keys, codes, tokens, tag):
        ds = self.ds_id(tag)
        rows, h = self.index.add(torch.as_tensor(keys).float().numpy(), tokens, ds)
        self.store.write(keys, codes, ds, rows, h)

    def delete(self, tag):
        if tag not in self.datasets:
            return 0, 0
        ds = self.datasets.index(tag)
        ns = self.store.delete_ds(ds)
        ni, remap = self.index.delete_ds(ds)
        self.store.remap_chunks(remap)
        return ns, ni

    def counts(self):
        out = {}
        for i, t in enumerate(self.datasets):
            out[t] = (int((self.store.ds.data == i).sum()), int((self.index.ds.data == i).sum()))
        return out

    def save(self, d):
        os.makedirs(d, exist_ok=True)
        for part, obj in (("store", self.store), ("index", self.index)):
            for name, arr in obj.arrays().items():
                arr.save(os.path.join(d, f"{part}_{name}.npy"))
        json.dump({"datasets": self.datasets, "clock": self.store.clock}, open(os.path.join(d, "memory.json"), "w"))

    def load(self, d, mmap=False):
        if not os.path.exists(os.path.join(d, "memory.json")):
            return
        meta = json.load(open(os.path.join(d, "memory.json")))
        self.datasets, self.store.clock = meta["datasets"], meta["clock"]
        for part, obj in (("store", self.store), ("index", self.index)):
            for name, arr in obj.arrays().items():
                arr.load(os.path.join(d, f"{part}_{name}.npy"), mmap)
            obj.invalidate(True)


